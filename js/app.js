// Función para cambiar idioma
function changeLanguage(lang) {
  const elements = document.querySelectorAll("[data-i18n]");
  elements.forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang] && translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  // Marcar botón activo
  document.querySelectorAll(".lang-btn").forEach(btn => btn.classList.remove("active"));
  if (lang === 'es') {
    document.querySelector(".lang-btn:nth-child(1)").classList.add("active");
  } else {
    document.querySelector(".lang-btn:nth-last-child(1)").classList.add("active");
  }

  localStorage.setItem("preferred_lang", lang);
}

// Cargar idioma guardado al iniciar
document.addEventListener("DOMContentLoaded", () => {
  const savedLang = localStorage.getItem("preferred_lang") || "es";
  changeLanguage(savedLang);
  calcularPresupuesto(false);
});

function actualizarInterfaz() {
  const prod = document.getElementById('tipoProducto').value;
  const cantInput = document.getElementById('cantInput');
  const cantLabel = document.getElementById('cantLabel');
  const comboWrap = document.getElementById('comboWrap');

  comboWrap.style.display = 'none';

  const currentLang = localStorage.getItem("preferred_lang") || "es";

  if (prod === 'serigrafia') {
    cantLabel.innerText = currentLang === 'en' ? 'Quantity (Minimum 100)' : 'Cantidad (Mínimo 100)';
    cantInput.value = Math.max(100, parseInt(cantInput.value, 10) || 100);
    cantInput.min = 100;
    cantInput.step = 50;
  } else if (prod === 'multicolor') {
    cantLabel.innerText = currentLang === 'en' ? 'Quantity (Minimum 500)' : 'Cantidad (Mínimo 500)';
    cantInput.value = Math.max(500, parseInt(cantInput.value, 10) || 500);
    cantInput.min = 500;
    cantInput.step = 50;
  } else if (prod === 'cinco_caras') {
    cantLabel.innerText = currentLang === 'en' ? 'Quantity (Minimum 500)' : 'Cantidad (Mínimo 500)';
    cantInput.value = Math.max(500, parseInt(cantInput.value, 10) || 500);
    cantInput.min = 500;
    cantInput.step = 50;
  } else if (prod === 'num40') {
    comboWrap.style.display = 'flex';
    const esCombo = document.getElementById('comboCheck').checked;
    if (esCombo) {
      cantLabel.innerText = currentLang === 'en' ? 'Quantity N° 40 (Minimum 1 - Combo Rate)' : 'Cantidad N° 40 (Mínimo 1 - Tarifa Combo)';
      cantInput.value = 1;
      cantInput.min = 1;
      cantInput.step = 1;
    } else {
      cantLabel.innerText = currentLang === 'en' ? 'Quantity N° 40 (Minimum 2 - Individual)' : 'Cantidad N° 40 (Mínimo 2 - Individual)';
      cantInput.value = 2;
      cantInput.min = 2;
      cantInput.step = 1;
    }
  }
  calcularPresupuesto();
}

function calcularPresupuesto(mostrarAlerta = false) {
  const prod = document.getElementById('tipoProducto').value;
  const cant = parseInt(document.getElementById('cantInput').value, 10);
  const out = document.getElementById('outCalc');
  const totalTxt = document.getElementById('montoTotalTxt');
  const detTxt = document.getElementById('descDetalleTxt');
  const waBtn = document.getElementById('waLinkBtn');
  const currentLang = localStorage.getItem("preferred_lang") || "es";

  let total = 0;
  let detalle = "";

  if (prod === 'serigrafia') {
    if (!cant || cant < 100) {
      out.style.display = 'none';
      if (mostrarAlerta) alert(currentLang === 'en' ? "Minimum order for 1-color screen printing is 100 units." : "El pedido mínimo para globos con impresión de 1 tinta es de 100 unidades.");
      return;
    }

    let unitario = 175;
    if (cant >= 2000) unitario = 110;
    else if (cant >= 1000) unitario = 150;

    total = cant * unitario;
    detalle = currentLang === 'en' ? `${cant} screen printed balloons (1 color) at ₡${unitario} each.` : `${cant} globos con impresión serigráfica (1 tinta) a ₡${unitario} c/u.`;
  } else if (prod === 'multicolor') {
    if (!cant || cant < 500) {
      out.style.display = 'none';
      if (mostrarAlerta) alert(currentLang === 'en' ? "Minimum order for multicolor printing up to 5 colors is 500 units." : "El pedido mínimo para impresión multicolor de hasta 5 colores es de 500 unidades.");
      return;
    }

    const unitario = 230;
    total = cant * unitario;
    detalle = currentLang === 'en' ? `${cant} multicolor printed balloons (up to 5 colors) at ₡${unitario} each.` : `${cant} globos con impresión multicolor de hasta 5 colores a ₡${unitario} c/u.`;
  } else if (prod === 'cinco_caras') {
    if (!cant || cant < 500) {
      out.style.display = 'none';
      if (mostrarAlerta) alert(currentLang === 'en' ? "Minimum order for 5-side printing is 500 units." : "El pedido mínimo para impresión de 5 caras es de 500 unidades.");
      return;
    }

    const unitario = 230;
    total = cant * unitario;
    detalle = currentLang === 'en' ? `${cant} balloons with 5-side printing (front, right, left, back, and top) at ₡${unitario} each.` : `${cant} globos con impresión a 5 caras (frente, derecha, izquierda, atrás y arriba) a ₡${unitario} c/u.`;
  } else if (prod === 'num40') {
    const esCombo = document.getElementById('comboCheck').checked;
    const minReq = esCombo ? 1 : 2;
    const unitario = esCombo ? 10000 : 12000;

    if (!cant || cant < minReq) {
      out.style.display = 'none';
      if (mostrarAlerta) {
        alert(esCombo ? (currentLang === 'en' ? "Minimum combo order for number 40 balloons is 1 unit." : "El pedido mínimo en combo para globos número 40 es de 1 unidad.") : (currentLang === 'en' ? "Minimum individual order for number 40 balloons is 2 units." : "El pedido mínimo individual de globos número 40 es de 2 unidades."));
      }
      return;
    }

    total = cant * unitario;
    detalle = currentLang === 'en' ? `${cant} Number 40 Balloon(s) at ₡${unitario.toLocaleString('es-CR')} each (${esCombo ? 'Combo rate applied' : 'Direct purchase'}).` : `${cant} Globo(s) Número 40 a ₡${unitario.toLocaleString('es-CR')} c/u (${esCombo ? 'Aplica tarifa combo con otro pedido' : 'Compra directa'}).`;
  }

  const totalFormateado = "₡" + total.toLocaleString('es-CR');
  totalTxt.innerText = `${totalFormateado} CRC`;
  detTxt.innerText = detalle;

  const textMsg = currentLang === 'en' ? `Hello Globo Studio CR! I want to quote: ${detalle} Estimated total: ${totalFormateado}. Do you have availability?` : `¡Hola Globo Studio CR! Quiero cotizar: ${detalle} Total estimado: ${totalFormateado}. ¿Tienen disponibilidad?`;
  const mensaje = encodeURIComponent(textMsg);
  waBtn.href = `https://wa.me/50671730138?text=${mensaje}`;

  out.style.display = 'block';
}
